#ifndef SCREENCAST_H
#define SCREENCAST_H

#include <stdint.h>
#include "../libacsiscsi/acsi.h"

// Resolution type of the sent screen - in TRAN_CMD_SENDSCREENCAST / TRAN_CMD_SCREENCASTPALETTE command byte 6 (cmd[5] in ce_cores),
// ce_cores stores it as byte 0 of the frame and web UI shows it. Must match SCREENCAST_RES_* in ce_cores
// screencastacsicommand.h and RES_* in webserver remote.html.

// ST resolutions - also ST compatible modes on TT and Falcon; values 0..2 are the old ST shifter mode, which older drivers sent
#define SCREENCAST_RES_ST_LOW       0x00    // 320 x 200, 16 colors
#define SCREENCAST_RES_ST_MID       0x01    // 640 x 200, 4 colors
#define SCREENCAST_RES_ST_HIGH      0x02    // 640 x 400, 2 colors

// TT resolutions
#define SCREENCAST_RES_TT_LOW       0x10    // 320 x 480, 256 colors
#define SCREENCAST_RES_TT_MID       0x11    // 640 x 480, 16 colors
#define SCREENCAST_RES_TT_HIGH      0x12    // 1280 x 960, 2 colors

// Falcon resolutions - bit field: bit 7 set, bit 6 width, bits 5-4 height, bits 2-0 bits per pixel
#define SCREENCAST_RES_FALCON       0x80
#define SCREENCAST_RES_F_W320       0x00
#define SCREENCAST_RES_F_W640       0x40
#define SCREENCAST_RES_F_H200       0x00
#define SCREENCAST_RES_F_H240       0x10
#define SCREENCAST_RES_F_H400       0x20
#define SCREENCAST_RES_F_H480       0x30
#define SCREENCAST_RES_F_BPP1       0x00    // 2 colors
#define SCREENCAST_RES_F_BPP2       0x01    // 4 colors
#define SCREENCAST_RES_F_BPP4       0x02    // 16 colors
#define SCREENCAST_RES_F_BPP8       0x03    // 256 colors
#define SCREENCAST_RES_F_BPP16      0x04    // true color

#define SCREENCAST_RES_FALCON_MODE(W, H, BPP)   (SCREENCAST_RES_FALCON | (W) | (H) | (BPP))

// typical Falcon resolutions - RGB / TV monitor
#define SCREENCAST_RES_FALCON_320x200x4     SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H200, SCREENCAST_RES_F_BPP2)
#define SCREENCAST_RES_FALCON_320x200x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H200, SCREENCAST_RES_F_BPP8)
#define SCREENCAST_RES_FALCON_320x200xTC    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H200, SCREENCAST_RES_F_BPP16)
#define SCREENCAST_RES_FALCON_640x200x16    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H200, SCREENCAST_RES_F_BPP4)
#define SCREENCAST_RES_FALCON_640x200x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H200, SCREENCAST_RES_F_BPP8)
#define SCREENCAST_RES_FALCON_640x200xTC    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H200, SCREENCAST_RES_F_BPP16)
#define SCREENCAST_RES_FALCON_320x400x16    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H400, SCREENCAST_RES_F_BPP4)
#define SCREENCAST_RES_FALCON_320x400x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H400, SCREENCAST_RES_F_BPP8)
#define SCREENCAST_RES_FALCON_320x400xTC    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H400, SCREENCAST_RES_F_BPP16)
#define SCREENCAST_RES_FALCON_640x400x4     SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H400, SCREENCAST_RES_F_BPP2)
#define SCREENCAST_RES_FALCON_640x400x16    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H400, SCREENCAST_RES_F_BPP4)
#define SCREENCAST_RES_FALCON_640x400x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H400, SCREENCAST_RES_F_BPP8)
#define SCREENCAST_RES_FALCON_640x400xTC    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H400, SCREENCAST_RES_F_BPP16)
// typical Falcon resolutions - VGA monitor
#define SCREENCAST_RES_FALCON_320x240x4     SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H240, SCREENCAST_RES_F_BPP2)
#define SCREENCAST_RES_FALCON_320x240x16    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H240, SCREENCAST_RES_F_BPP4)
#define SCREENCAST_RES_FALCON_320x240x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H240, SCREENCAST_RES_F_BPP8)
#define SCREENCAST_RES_FALCON_320x240xTC    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H240, SCREENCAST_RES_F_BPP16)
#define SCREENCAST_RES_FALCON_640x240x4     SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H240, SCREENCAST_RES_F_BPP2)
#define SCREENCAST_RES_FALCON_640x240x16    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H240, SCREENCAST_RES_F_BPP4)
#define SCREENCAST_RES_FALCON_640x240x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H240, SCREENCAST_RES_F_BPP8)
#define SCREENCAST_RES_FALCON_320x480x16    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H480, SCREENCAST_RES_F_BPP4)
#define SCREENCAST_RES_FALCON_320x480x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H480, SCREENCAST_RES_F_BPP8)
#define SCREENCAST_RES_FALCON_320x480xTC    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W320, SCREENCAST_RES_F_H480, SCREENCAST_RES_F_BPP16)
#define SCREENCAST_RES_FALCON_640x480x2     SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H480, SCREENCAST_RES_F_BPP1)
#define SCREENCAST_RES_FALCON_640x480x4     SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H480, SCREENCAST_RES_F_BPP2)
#define SCREENCAST_RES_FALCON_640x480x16    SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H480, SCREENCAST_RES_F_BPP4)
#define SCREENCAST_RES_FALCON_640x480x256   SCREENCAST_RES_FALCON_MODE(SCREENCAST_RES_F_W640, SCREENCAST_RES_F_H480, SCREENCAST_RES_F_BPP8)

#define SCREENCAST_RES_UNKNOWN      0xff    // couldn't tell

// screen data sizes - ST size is also sent for the resolutions which are not supported yet (Falcon, unknown)
#define SCREENCAST_SCREEN_SIZE_ST   32000
#define SCREENCAST_SCREEN_SIZE_TT   153600

// bigger screens are sent in parts of up to this size (in command bytes 10-12 is the offset of the part in the screen),
// as one DMA transfer can't do more than MAXSECTORS
#define SCREENCAST_PART_SIZE        (MAXSECTORS * 512)

// all of these read video registers directly (no OS calls), so they are safe to call from VBL; they use 'machine'
// (MACHINE_*), which findDevice() sets
uint8_t  screencastGetRes(void);                            // current resolution as SCREENCAST_RES_*
uint32_t screencastScreenSize(uint8_t res);                 // size of screen data which is sent for this resolution
uint32_t screencastGetPalette(uint8_t res, uint8_t *bfr);   // copy palette of this resolution to bfr (up to 512 B), returns its size
uint8_t *screencastScreenAddress(void);                     // address of the displayed screen, from video registers

#endif
