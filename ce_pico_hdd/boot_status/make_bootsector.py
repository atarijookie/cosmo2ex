#!/usr/bin/env python3
"""Builds the boot status sector of ce_pico_hdd - see ../boot_status.cpp.

Assembles status.s (m68k-atari-mint-as / objcopy) into a 512 B root sector and writes
  ../boot_status_data.h   the sector, compiled into the firmware (committed, as Arduino can't run this)
  bootsector.bin          the same sector (devno 0, checksum done), to look at / try in an emulator

The device sets devno (BOOT_STATUS_DEVNO_OFFSET) and the checksum word for the ID it serves the sector on.

Run it from anywhere after changing status.s: python3 make_bootsector.py
"""

import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_HEADER = os.path.join(HERE, '..', 'boot_status_data.h')
OUT_BIN = os.path.join(HERE, 'bootsector.bin')

AS = 'm68k-atari-mint-as'
OBJCOPY = 'm68k-atari-mint-objcopy'
NM = 'm68k-atari-mint-nm'

BPS = 512
CODE_MAX = 0x1c2            # the partition table + checksum start here - stay empty (no partitions)


def assemble():
    """Returns the code and the offset of the devno byte in it."""
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, 'status.o')
        binary = os.path.join(tmp, 'status.bin')
        subprocess.check_call([AS, '-m68000', '-o', obj, os.path.join(HERE, 'status.s')])
        subprocess.check_call([OBJCOPY, '-O', 'binary', '-j', '.text', obj, binary])
        symbols = subprocess.check_output([NM, obj]).decode().split('\n')
        devno = [int(line.split()[0], 16) for line in symbols if line.endswith(' devno')]
        if len(devno) != 1:
            sys.exit('symbol devno not found in status.s')
        with open(binary, 'rb') as f:
            return f.read(), devno[0]


def make_sector(code):
    if len(code) > CODE_MAX:
        sys.exit('boot code too long: %d B, max %d B' % (len(code), CODE_MAX))

    sector = bytearray(BPS)
    sector[:len(code)] = code

    # executable: big endian words sum up to 0x1234
    total = sum(struct.unpack('>255H', sector[:510])) & 0xffff
    struct.pack_into('>H', sector, 510, (0x1234 - total) & 0xffff)
    return sector


def write_header(sector, code_len, devno_offset):
    lines = []
    lines.append('// Generated by boot_status/make_bootsector.py - don\'t edit, run the script again.')
    lines.append('// Boot status sector: code %d of %d B.' % (code_len, CODE_MAX))
    lines.append('#ifndef __BOOT_STATUS_DATA_H__')
    lines.append('#define __BOOT_STATUS_DATA_H__')
    lines.append('')
    lines.append('#include <cstdint>')
    lines.append('')
    lines.append('#define BOOT_STATUS_DEVNO_OFFSET    %d      // ACSI 0..7, SCSI 8..15' % devno_offset)
    lines.append('')
    lines.append('static const uint8_t bootStatusSector[512] = {')
    for row in range(0, BPS, 16):
        lines.append('    ' + ', '.join('0x%02x' % b for b in sector[row:row + 16]) + ',')
    lines.append('};')
    lines.append('')
    lines.append('#endif')

    with open(OUT_HEADER, 'w') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    code, devno_offset = assemble()
    sector = make_sector(code)
    write_header(sector, len(code), devno_offset)

    with open(OUT_BIN, 'wb') as f:
        f.write(sector)

    print('boot code %d / %d B -> %s, %s' % (len(code), CODE_MAX, os.path.relpath(OUT_HEADER), os.path.relpath(OUT_BIN)))


if __name__ == '__main__':
    main()
