package main

// Text for the Atari's toolbar: plain printable ASCII only. Sent as UTF-8, the ST would show each byte as one of its
// own characters - stray German letters and symbols. Accented letters lose their accents (č -> c), typographic
// punctuation becomes ASCII (– -> -, “ -> "), anything else (·, •, emoji, other scripts) a space; spaces are merged.

import "strings"

func toAtariASCII(s string) string {
	var sb strings.Builder
	lastSpace := true // drops leading spaces
	put := func(t string) {
		for i := 0; i < len(t); i++ {
			c := t[i]
			if c == ' ' {
				if lastSpace {
					continue
				}
				lastSpace = true
			} else {
				lastSpace = false
			}
			sb.WriteByte(c)
		}
	}
	for _, r := range s {
		switch {
		case r >= 0x20 && r < 0x7f:
			put(string(r))
		default:
			if t, ok := asciiFor[r]; ok {
				put(t)
			} else {
				put(" ") // tab, newline, and what the ST can't show
			}
		}
	}
	return strings.TrimRight(sb.String(), " ")
}

