static int compareItems(const void* key, const void* item)
{
    uint32_t cp = *(const uint32_t*) key;
    uint32_t itemCp = ((const TranslitItem*) item)->codePoint;
    return (cp < itemCp) ? -1 : ((cp > itemCp) ? 1 : 0);
}

// Decode one UTF-8 char at pos. On success returns its length (2..4) and the code point, on invalid sequence returns 0.
static int decodeUtf8(const std::string& s, size_t pos, uint32_t& cp)
{
    unsigned char c = (unsigned char) s[pos];
    int len;

    if(c >= 0xC2 && c <= 0xDF) {        // 2 bytes (0xC0, 0xC1 would be overlong)
        len = 2;
        cp = c & 0x1F;
    } else if(c >= 0xE0 && c <= 0xEF) { // 3 bytes
        len = 3;
        cp = c & 0x0F;
    } else if(c >= 0xF0 && c <= 0xF4) { // 4 bytes
        len = 4;
        cp = c & 0x07;
    } else {                            // continuation byte or invalid lead byte
        return 0;
    }

    if(pos + len > s.size()) {          // truncated
        return 0;
    }

    for(int i=1; i<len; i++) {
        unsigned char cc = (unsigned char) s[pos + i];

        if((cc & 0xC0) != 0x80) {       // not a continuation byte
            return 0;
        }

        cp = (cp << 6) | (cc & 0x3F);
    }

    // reject overlong encodings, surrogates and values above U+10FFFF
    if((len == 3 && cp < 0x800) || (len == 4 && cp < 0x10000) || (cp >= 0xD800 && cp <= 0xDFFF) || cp > 0x10FFFF) {
        return 0;
    }

    return len;
}

void transliterateToAscii(const std::string& in, std::string& out)
{
    out.clear();
    out.reserve(in.size());

    size_t pos = 0;
    while(pos < in.size()) {
        unsigned char c = (unsigned char) in[pos];

        if(c < 0x80) {                  // plain ASCII - copy
            out += (char) c;
            pos++;
            continue;
        }

        uint32_t cp;
        int len = decodeUtf8(in, pos, cp);

        if(len == 0) {                  // not valid UTF-8 (e.g. name in some 8-bit codepage) - copy the byte, it will be replaced with '_' later
            out += (char) c;
            pos++;
            continue;
        }

        pos += len;

        const TranslitItem* item = (const TranslitItem*) bsearch(&cp, translitTable, sizeof(translitTable) / sizeof(translitTable[0]), sizeof(TranslitItem), compareItems);

        if(item) {                      // known char - use its ASCII replacement (might be also empty, e.g. Cyrillic soft sign)
            out += item->ascii;
        } else {                        // unknown char (e.g. CJK) - one '_' for the whole char, not one for each of its bytes
            out += '_';
        }
    }
}
